export type Lang = 'es' | 'en'
export type Strings = typeof strings.es

const LangContext = createContext<{ lang: Lang; t: Strings; toggle: () => void }>({
  lang: 'es',
  t: strings.es,
  toggle: () => {},
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem('lang') as Lang) || 'es')
  const toggle = () => {
    const next = lang === 'es' ? 'en' : 'es'
    setLang(next)
    localStorage.setItem('lang', next)
  }
  return <LangContext.Provider value={{ lang, t: strings[lang], toggle }}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}
